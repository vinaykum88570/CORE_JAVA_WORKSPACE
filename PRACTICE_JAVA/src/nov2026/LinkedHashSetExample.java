package nov2026;

import java.util.LinkedHashSet;

public class LinkedHashSetExample {
    public static void main(String[] args) {
        LinkedHashSet <Integer> lhs= new LinkedHashSet<>();
        lhs.add(56);
        lhs.add(22);
        lhs.add(58);
        lhs.add(74);
        lhs.add(10);
        System.out.println(lhs);
    }
}
